// 🧭 registry.ts — le vocabulaire d'icônes de qoe.fi
// =====================================================================
// 📖 Une seule liste, nommée par l'intention et non par le dessin.
//
//    Pourquoi un registre et pas des imports Lucide au fil des écrans :
//    les apps importaient 74 icônes différentes, souvent deux dessins pour
//    la même idée (`Trash` ici, `Trash2` là) et cinq épaisseurs de trait.
//    Le registre donne UN nom par concept, donc changer le dessin d'une
//    action se fait ici et nulle part ailleurs.
//
// 🎯 Les clés sont en kebab-case (`arrow-up-right`), pas en PascalCase :
//    un nom d'icône se lit dans le JSX et se cherche dans le lab, il doit
//    rester une chaîne stable, pas un identifiant de composant.
// =====================================================================

